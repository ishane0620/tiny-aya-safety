"""Recompute every reported metric from the saved answers and write results/.

    python scripts/compute_metrics.py            # uses data/results/pipeline5_answers.jsonl
    python scripts/compute_metrics.py path.jsonl # e.g. answers regenerated by notebook 05

Writes results/metrics.json, results/RESULTS_TABLES.md and results/figures/*.png.
Needs no GPU and no network.
"""
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from tiny_aya_safety import metrics  # noqa: E402

LABELS = {"baseline": "Original", "restricted": "Restricted LoRA\n(layer 18)", "broad": "Broad LoRA\n(all layers)"}
COLORS = {"baseline": "#888780", "restricted": "#1D9E75", "broad": "#7F77DD"}


def r1(x):
    """One decimal, rounding halves up (29/80 = 36.25% -> 36.3%), immune to float noise."""
    from decimal import ROUND_HALF_UP, Decimal
    return str((Decimal(str(round(x, 10))) * 100).quantize(Decimal("0.1"), rounding=ROUND_HALF_UP))


def signed(x):
    v = r1(x)
    return v if v.startswith("-") else "+" + v


def pct(x):
    return f"{r1(x)}%"


def tables_md(m, df) -> str:
    h = m["headline"]
    lines = ["# Results tables (recomputed from `pipeline5_answers.jsonl`)", "",
             "Qwen3Guard-Gen-0.6B judgments on the 228 seed-disjoint validation prompts (`analysis` split).",
             "Not human-validated, and not the untouched `heldout` split.", "",
             "## Headline", "",
             "| Metric | Original | Restricted LoRA | Broad LoRA |", "|---|---:|---:|---:|"]
    rows = [("Unsafe answers, harmful prompts that should be declined", "unsafe_rate_decline", "unsafe_decline"),
            ("Needless refusals, harmless twins", "needless_refusal_rate_twins", "needless_refusal_twins"),
            ("Refusals, borderline answer-carefully prompts", "refusal_rate_answer_carefully", "refusal_answer_carefully")]
    for title, rate, count in rows:
        lines.append(f"| {title} | " + " | ".join(f"{pct(h[mm][rate])} ({h[mm][count]})" for mm in metrics.MODELS) + " |")
    lines.append("| Average answer length on harmless twins (characters) | " +
                 " | ".join(f"{h[mm]['mean_harmless_answer_chars']:,.0f}" for mm in metrics.MODELS) + " |")
    lines += ["", "Unsafe-rate denominators exclude answers labelled Controversial or Unparsed "
              "(original 3, restricted 1, broad 0 among the 118 decline prompts).", ""]

    lines += ["## Paired before/after (same prompt, two models; exact McNemar test)", "",
              "| Comparison | n | improved | worsened | unchanged | p |", "|---|---:|---:|---:|---:|---:|"]
    for arm in ("restricted", "broad"):
        p = m["paired"][arm]["harmful_unsafe"]
        lines.append(f"| {arm}: harmful prompts, unsafe -> safe vs safe -> unsafe | {p['n_paired']} | {p['to_good']} | "
                     f"{p['to_bad']} | {p['both_0'] + p['both_1']} | {p['p_exact_mcnemar']:.2g} |")
        p = m["paired"][arm]["twin_refused"]
        lines.append(f"| {arm}: harmless twins, refused -> answered vs answered -> refused | {p['n_paired']} | "
                     f"{p['to_good']} | {p['to_bad']} | {p['both_0'] + p['both_1']} | {p['p_exact_mcnemar']:.2g} |")
    p = m["paired"]["broad_vs_restricted"]["twin_refused"]
    lines.append(f"| broad vs restricted: harmless twins (worsened = broad refuses, restricted answers) | "
                 f"{p['n_paired']} | {p['to_good']} | {p['to_bad']} | {p['both_0'] + p['both_1']} | {p['p_exact_mcnemar']:.2g} |")

    lines += ["", "## Seed-level robustness", "",
              "Several validation prompts are rewrites of one source seed, so prompt-level tests overstate the "
              "sample size. Here seeds are the unit: a 95% bootstrap interval resampling seeds, and a sign test "
              "counting seeds whose rate went down vs up.", "",
              "| Comparison | prompts / seeds | change vs original | 95% CI (seed bootstrap) | seeds down / up | sign-test p |",
              "|---|---:|---:|---:|---:|---:|"]
    for arm in ("restricted", "broad"):
        for key, title in (("decline_unsafe", "unsafe rate, decline prompts"), ("twin_refused", "refusal rate, harmless twins")):
            b, s = m["seed_level"][arm][f"{key}_bootstrap"], m["seed_level"][arm][f"{key}_sign"]
            lines.append(f"| {arm}: {title} | {b['n_prompts']} / {b['n_seeds']} | {signed(b['diff'])} pts | "
                         f"[{signed(b['ci95_low'])}, {signed(b['ci95_high'])}] | {s['seeds_down']} / {s['seeds_up']} | {s['p_sign']:.2g} |")

    lines += ["", "## US vs neutral framing (Mantel-Haenszel, stratified by language, harmful prompts)", "",
              "| Model | odds ratio | p | n |", "|---|---:|---:|---:|"]
    for mm, r in m["culture_gap_mh"].items():
        orr = "undefined (no unsafe answers left in one condition)" if r["or_mh"] != r["or_mh"] else f"{r['or_mh']:.2f}"
        lines.append(f"| {mm} | {orr} | {r['p_mh']:.3g} | {r['n_rows']} |")

    lines += ["", "## By jailbreak technique (harmful: unsafe answers; twins: refusals)", "",
              "| Technique | " + " | ".join(f"{mm} harmful unsafe" for mm in metrics.MODELS) + " | " +
              " | ".join(f"{mm} twin refused" for mm in metrics.MODELS) + " |", "|---|" + "---:|" * 6]
    for fr in ("control", "rp", "fc", "rs"):
        cells = []
        for kind, col in (("harmful", "unsafe"), ("twin", "refused")):
            for mm in metrics.MODELS:
                g = df[(df["model"] == mm) & (df["kind"] == kind) & (df["framing"] == fr)][col].dropna()
                cells.append(f"{int(g.sum())}/{len(g)}")
        lines.append(f"| {fr} | " + " | ".join(cells) + " |")
    lines += ["", "## By language", "", "| Language | " + " | ".join(f"{mm} harmful unsafe" for mm in metrics.MODELS) + " | " +
              " | ".join(f"{mm} twin refused" for mm in metrics.MODELS) + " |", "|---|" + "---:|" * 6]
    for lang in ("en", "ja"):
        cells = []
        for kind, col in (("harmful", "unsafe"), ("twin", "refused")):
            for mm in metrics.MODELS:
                g = df[(df["model"] == mm) & (df["kind"] == kind) & (df["language"] == lang)][col].dropna()
                cells.append(f"{int(g.sum())}/{len(g)}")
        lines.append(f"| {lang} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def figures(m, out: Path):
    out.mkdir(parents=True, exist_ok=True)
    h = m["headline"]
    panels = [("unsafe_rate_decline", "Unsafe answers\n(harmful prompts to decline, n≈118)", "lower is safer"),
              ("needless_refusal_rate_twins", "Needless refusals\n(harmless twins, n=80)", "lower is more helpful"),
              ("refusal_rate_answer_carefully", "Refusals on borderline\n(answer-carefully, n=30)", "lower is more helpful")]
    fig, axes = plt.subplots(1, 3, figsize=(12, 4.2))
    for ax, (key, title, sub) in zip(axes, panels):
        vals = [100 * h[mm][key] for mm in metrics.MODELS]
        bars = ax.bar([LABELS[mm] for mm in metrics.MODELS], vals, color=[COLORS[mm] for mm in metrics.MODELS])
        for b, v, mm in zip(bars, vals, metrics.MODELS):
            ax.text(b.get_x() + b.get_width() / 2, v + 0.8, pct(h[mm][key]), ha="center", fontsize=10)
        ax.set_title(title, fontsize=11)
        ax.set_xlabel(sub, fontsize=9, color="#555")
        ax.set_ylim(0, max(vals) * 1.25 + 2)
        ax.spines[["top", "right"]].set_visible(False)
        ax.tick_params(axis="x", labelsize=9)
    axes[0].set_ylabel("% of judged answers")
    fig.suptitle("Tiny Aya Water: original vs safety LoRA (Qwen3Guard judgments, 228 seed-disjoint validation prompts)",
                 fontsize=11)
    fig.tight_layout()
    fig.savefig(out / "headline_metrics.png", dpi=160)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(6.2, 4.4))
    for mm in metrics.MODELS:
        x, y = 100 * h[mm]["needless_refusal_rate_twins"], 100 * h[mm]["unsafe_rate_decline"]
        ax.scatter(x, y, s=140, color=COLORS[mm], zorder=3)
        ax.annotate(LABELS[mm].replace("\n", " "), (x, y), textcoords="offset points", xytext=(8, 6), fontsize=9)
    ax.set_xlabel("Needless refusals on harmless twins (%)  → less helpful")
    ax.set_ylabel("Unsafe answers on decline prompts (%)  → less safe")
    ax.set_xlim(0, 45); ax.set_ylim(-1, 13)
    ax.set_title("Safety vs helpfulness trade-off (bottom-left is best)", fontsize=11)
    ax.grid(alpha=0.3); ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(out / "tradeoff.png", dpi=160)
    plt.close(fig)


def main():
    answers = Path(sys.argv[1]) if len(sys.argv) > 1 else REPO / "data/results/pipeline5_answers.jsonl"
    df = metrics.load_answers(answers)
    m = metrics.compute_all(df)
    m["source"] = str(answers.relative_to(REPO)) if answers.is_relative_to(REPO) else str(answers)
    out = REPO / "results"
    metrics.to_json(m, out / "metrics.json")
    (out / "RESULTS_TABLES.md").write_text(tables_md(m, df), encoding="utf-8")
    figures(m, out / "figures")
    print("wrote results/metrics.json, results/RESULTS_TABLES.md, results/figures/")


if __name__ == "__main__":
    main()
